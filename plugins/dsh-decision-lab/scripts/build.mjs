import { build } from 'esbuild';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

/** Keep React external: DSH owns the React instance and module registry. */
export async function buildClient(entry, outfile) {
  await build({
    entryPoints: [entry], outfile, bundle: true, platform: 'browser', format: 'cjs',
    target: ['es2022'], external: ['react'], legalComments: 'inline',
    banner: { js: '// Generated by scripts/build.mjs; edit src/client.jsx.\nwindow.__ModuleLoader__.load({id:"dsh-decision-lab",factory(require){const module={exports:{}};const exports=module.exports;' },
    footer: { js: 'return module.exports;}});' },
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  await buildClient(resolve(root, 'src/client.jsx'), resolve(root, 'client.js'));
}
