// Fast rebuild: regenerates client.js from a pre-built esbuild output.
//
// The full `npm run build` also rewrites lib/assets/* (mermaid, echarts, three).
// With dependency versions that differ from upstream's, that churns several
// thousand lines even when nothing changed. If you only edited src/, use this:
//
//   1. node_modules/@esbuild/win32-x64/esbuild.exe src/client.jsx \
//        --bundle --format=cjs --platform=browser --target=es2022 \
//        --external:react --external:react/jsx-runtime --external:react-dom \
//        --external:react-dom/client --jsx=transform --legal-comments=none \
//        --outfile=build-tmp/client.raw.js
//   2. node scripts/build-client.mjs
//
// The esbuild CLI is invoked directly rather than through the JS API because
// sandboxed hosts block the stdio pipe that API needs (`spawn EPERM`).

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const RAW = process.argv[2] ?? 'build-tmp/client.raw.js';
const { name, version } = JSON.parse(await readFile('package.json', 'utf8'));

async function collect(dir, out = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) await collect(path, out);
    else if (path !== 'lib/build-info.js') out.push(path);
  }
  return out;
}

const paths = ['index.js', 'package.json', ...await collect('src'), ...await collect('lib'), ...await collect('skills')].sort();
const hash = createHash('sha256');
for (const path of paths) {
  hash.update(path); hash.update('\0');
  hash.update(await readFile(path)); hash.update('\0');
}
const sourceHash = hash.digest('hex');

await writeFile('lib/build-info.js', `// Generated by npm run build.\nexport const BUILD_INFO = Object.freeze(${JSON.stringify({ version, id: `${version}+${sourceHash.slice(0, 12)}`, sourceHash })});\n`);

const raw = await readFile(RAW, 'utf8');
await writeFile('client.js', `// Generated by npm run build.\nwindow.__ModuleLoader__.load({id:"${name}",factory:(require)=>{\nvar module={exports:{}};var exports=module.exports;\n${raw}\nreturn module.exports;}});\n`);

console.log(`client.js rebuilt for ${name}@${version} (${sourceHash.slice(0, 12)})`);
