import { build } from 'esbuild';
import { writeFile, readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import './build-visual.mjs';
import './build-mechanism.mjs';
const standalone=await build({entryPoints:['src/export-runtime.js'],bundle:true,write:false,format:'iife',platform:'browser',target:'es2022',legalComments:'none'});
await writeFile('lib/export-runtime-bundle.js',`// Generated by scripts/build.mjs.\nexport const EXPORT_RUNTIME=${JSON.stringify(standalone.outputFiles[0].text)};\n`);
async function collect(dir) {
  const result = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) result.push(...await collect(path)); else if (path !== 'lib/build-info.js') result.push(path);
  }
  return result;
}
const paths = ['index.js', 'package.json', ...await collect('src'), ...await collect('lib'), ...await collect('skills')].sort(), hash = createHash('sha256');
for (const path of paths) { hash.update(path); hash.update('\0'); hash.update(await readFile(path)); hash.update('\0'); }
const sourceHash = hash.digest('hex'), { version } = JSON.parse(await readFile('package.json', 'utf8'));
await writeFile('lib/build-info.js', `// Generated by npm run build.\nexport const BUILD_INFO = Object.freeze(${JSON.stringify({ version, id: `${version}+${sourceHash.slice(0, 12)}`, sourceHash })});\n`);
const result = await build({ entryPoints: ['src/client.jsx'], bundle: true, write: false, format: 'cjs', platform: 'browser', target: 'es2022', external: ['react','react/jsx-runtime','react-dom','react-dom/client'], jsx: 'transform', legalComments: 'none' });
await writeFile('client.js', `// Generated by npm run build.\nwindow.__ModuleLoader__.load({id:"dsh-motion-ui",factory:(require)=>{\nvar module={exports:{}};var exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports;}});\n`);
